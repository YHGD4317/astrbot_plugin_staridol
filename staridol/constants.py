@dataclass
class TierInfo:
    """资产档位信息。"""

    tier: int  # 已达成的档位数
    next_threshold: int | None  # 下一档门槛（w），None 表示已满档
    quest_count: int  # 当前每日事务量
    reward_multiplier: float  # 奖励倍率


def tier_of(total_asset: int, base_quest: int = DEFAULT_DAILY_QUEST) -> TierInfo:
    """根据总资产计算档位信息。"""
    tier = 0
    for threshold in ASSET_TIERS:
        if total_asset >= threshold:
            tier += 1
        else:
            break
    next_threshold = ASSET_TIERS[tier] if tier < len(ASSET_TIERS) else None
    return TierInfo(
        tier=tier,
        next_threshold=next_threshold,
        quest_count=base_quest + tier,
        reward_multiplier=1.0 + tier * 0.35,
    )


